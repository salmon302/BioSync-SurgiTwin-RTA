"""Write a replay capture for the srtra_bridge replay source from the synthetic trajectories.

The formulas match bridge_node.cpp fill_tick (synthetic mode, 0.2 Hz path, 8 modal coefficients).
The output is synthetic data from this generator. It is not SOFA output. The capture schema is
documented in sim/bridge/README.md (section "Replay source").

Usage: python make_replay_capture.py --rate 500 --duration 60 --out <file.csv>
Writes <file.csv> and <file.meta.json> (provenance: source, generator, rows, SHA-256 of the CSV).
"""

import argparse
import hashlib
import json
import math
import os
import sys

TWO_PI = 6.283185307179586
PATH_HZ = 0.2
MODE_COUNT = 8

FIXED_HEADER = [
    'tick', 'time_s', 'pos_x', 'pos_y', 'pos_z', 'quat_x', 'quat_y', 'quat_z', 'quat_w',
    'force_x', 'force_y', 'force_z', 'torque_x', 'torque_y', 'torque_z',
]


def row_values(tick, rate):
    t = tick / rate
    w = TWO_PI * PATH_HZ * t
    yaw = 0.3 * math.sin(w)
    pose = [
        0.02 * math.sin(w),
        0.01 * math.sin(2.0 * w),
        0.10 + 0.005 * math.cos(w),
        0.0,
        0.0,
        math.sin(0.5 * yaw),
        math.cos(0.5 * yaw),
    ]
    wrench = [
        1.5 * math.sin(w + 0.5),
        0.8 * math.cos(w),
        2.0 + 0.5 * math.sin(2.0 * w),
        0.02 * math.cos(w),
        0.01 * math.sin(2.0 * w),
        0.005 * math.sin(w + 1.0),
    ]
    modes = []
    for k in range(MODE_COUNT):
        f = float(k + 1)
        modes.append((0.002 / f) * math.sin(f * w + 0.3 * f))
    return pose, wrench, modes


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--rate', type=int, default=500)
    parser.add_argument('--duration', type=int, default=60)
    parser.add_argument('--out', required=True)
    args = parser.parse_args(argv[1:])
    rows = args.rate * args.duration
    header = FIXED_HEADER + ['mode_%d' % k for k in range(MODE_COUNT)]
    lines = [','.join(header)]
    for tick in range(rows):
        pose, wrench, modes = row_values(tick, args.rate)
        fields = ['%d' % tick, '%.9f' % (tick / args.rate)]
        fields += ['%.12g' % v for v in pose + wrench + modes]
        lines.append(','.join(fields))
    payload = ('\n'.join(lines) + '\n').encode('utf-8')
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, 'wb') as fh:
        fh.write(payload)
    meta = {
        'schema': 'srtra-bridge-replay-capture-meta/1',
        'source': 'synthetic',
        'provenance': 'generated by sim/bridge/tools/make_replay_capture.py from the synthetic '
                      'trajectories of bridge_node (fill_tick). Not SOFA data.',
        'rate_hz': args.rate,
        'rows': rows,
        'modes': MODE_COUNT,
        'csv_file': os.path.basename(args.out),
        'csv_sha256': hashlib.sha256(payload).hexdigest(),
    }
    meta_path = os.path.splitext(args.out)[0] + '.meta.json'
    with open(meta_path, 'w', encoding='utf-8') as fh:
        json.dump(meta, fh, indent=2)
        fh.write('\n')
    print(json.dumps({'rows': rows, 'csv': args.out, 'meta': meta_path,
                      'csv_sha256': meta['csv_sha256']}, indent=2))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
